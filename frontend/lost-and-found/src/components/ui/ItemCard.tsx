import { AlertCircle, CheckCircle2, ShieldCheck, User, X } from 'lucide-react'
import { Button } from './Button'
import { claimService } from '../../services/claimService'
import { useState } from 'react'

export type Item = {
  id: number
  type: 'lost' | 'found'
  title: string
  description: string
  tags: string[]
  location: string
  date: string
  category: string
  status: 'active' | 'matched' | 'resolved'
  imageUrl?: string
  user_id?: string | null
}

type ItemCardProps = {
  item: Item
  navigate: (page: string, itemId?: number) => void
  currentUserId?: string | null
}

export function ItemCard({ item, navigate, currentUserId }: ItemCardProps) {
  const isMatched = item.status === 'matched'

  // Check if the item belongs to the currently logged in user
  const isUserItem = currentUserId ? item.user_id === currentUserId : false

  // Modal State for custom UI notifications
  const [modalState, setModalState] = useState<{
    isOpen: boolean
    title: string
    message: string
    type: 'success' | 'error'
  }>({
    isOpen: false,
    title: '',
    message: '',
    type: 'success'
  })

  const handleActionClick = async (e: React.MouseEvent) => {
    e.stopPropagation() // Prevents card's row onClick from firing
    try {
      // Calling backend service to initialize the claim
      const result = await claimService.createClaim({ item_id: item.id.toString() })
      setModalState({
        isOpen: true,
        title: 'Claim Initiated',
        message:
          result.message ||
          'Claim created successfully. Verification questions are being generated by the system. Check your Claims tab shortly to proceed.',
        type: 'success'
      })
    } catch (error: any) {
      const message =
        error?.response?.data?.detail ||
        error?.message ||
        'Failed to create claim. Please try again.'
      setModalState({
        isOpen: true,
        title: 'Claim Request Failed',
        message,
        type: 'error'
      })
    }
  }
  
  const handleModalClose = () => {
    setModalState(prev => ({ ...prev, isOpen: false }))
  }

  return (
    <>
    <div
      onClick={() => navigate('detail', item.id)}
      className="border-b border-[#0E0D0B]/10 px-8 py-4 bg-[#FAF6EC] hover:bg-[#0E0D0B]/5 transition-colors cursor-pointer flex flex-col md:grid gap-4 items-start md:items-center"
      style={{ gridTemplateColumns: '80px 1fr 140px 140px 90px 130px' }}
    >
      {/* 1. TYPE */}
      <div className="flex flex-col gap-1">
        <span
          className={`font-mono text-[10px] px-2 py-0.5 uppercase tracking-wider font-bold w-fit ${
            item.type === 'lost'
              ? 'bg-[#D93B2B] text-[#FAF6EC]'
              : 'bg-[#06C167] text-[#0E0D0B]'
          }`}
        >
          {item.type}
        </span>
        {item.status === 'matched' && (
          <span className="font-mono text-[9px] px-1.5 py-0.5 bg-[#7C3AED] text-[#FAF6EC] uppercase tracking-wider w-fit">
            Match
          </span>
        )}
      </div>

      {/* 2. ITEM & DESCRIPTION */}
      <div className="flex items-start gap-3 min-w-0">
        {item.imageUrl && (
          <img
            src={item.imageUrl}
            alt={item.title}
            className="w-12 h-12 object-cover border border-[#0E0D0B]/10 shrink-0"
          />
        )}
        <div className="min-w-0">
          <h3 className="font-bold text-sm text-[#0E0D0B] truncate" style={{ fontFamily: 'Fraunces, serif' }}>
            {item.title}
          </h3>
          <p className="text-xs text-[#0E0D0B]/70 line-clamp-1 mt-0.5">
            {item.description}
          </p>
        </div>
      </div>

      {/* 3. CATEGORY & TAGS */}
      <div className="flex flex-col gap-1.5">
        <span className="font-mono text-[10px] text-[#0E0D0B]/65 uppercase">
          [{item.category}]
        </span>
        <div className="flex flex-wrap gap-1">
          {item.tags.slice(0, 3).map((tag, idx) => (
            <span
              key={idx}
              className="font-mono text-[9px] px-1.5 py-0.5 bg-[#0E0D0B] text-[#FAF6EC] uppercase"
            >
              #{tag}
            </span>
          ))}
          {item.tags.length > 3 && (
            <span className="font-mono text-[9px] text-[#0E0D0B]/65 self-center">
              +{item.tags.length - 3}
            </span>
          )}
        </div>
      </div>

      {/* 4. LOCATION */}
      <div className="font-mono text-xs text-[#0E0D0B]/65 truncate w-full">
        {item.location}
      </div>

      {/* 5. DATE */}
      <div className="font-mono text-xs text-[#0E0D0B]/65 whitespace-nowrap">
        {item.date}
      </div>

      {/* 6. ACTION BUTTON */}
      <div className="justify-self-end w-full md:w-auto" onClick={e => e.stopPropagation()}>
          {isUserItem ? (
            /* User's own posted item indicator */
            <div className="font-mono text-[9px] uppercase font-bold px-2.5 py-1.5 border border-[#0E0D0B]/20 text-[#0E0D0B]/70 flex items-center gap-1 justify-center whitespace-nowrap bg-white">
              <User size={11} /> Your Item
            </div>
          ) : isMatched ? (
            <div className="font-mono text-[9px] uppercase font-bold px-2.5 py-1.5 border border-[#0E0D0B]/20 text-[#0E0D0B]/50 flex items-center gap-1 justify-center whitespace-nowrap bg-transparent">
              <ShieldCheck size={11} /> Claim Pending
            </div>
          ) : (
            /* Active items show the CLAIM button */
            <Button 
              variant="outline" 
              size="sm"
              onClick={handleActionClick}
              className="w-full md:w-auto font-mono text-[9px] uppercase tracking-wider py-1 px-3 whitespace-nowrap border-[#0E0D0B]/20 text-[#0E0D0B] hover:bg-[#0E0D0B] hover:text-[#FAF6EC]"
            >
              <ShieldCheck size={11} /> Claim
            </Button>
          )}
        </div>
    </div>
    
    {/* Styled Institutional Modal */}
      {modalState.isOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-[#0E0D0B]/60 backdrop-blur-xs">
          <div className="bg-[#FAF6EC] border border-[#0E0D0B] shadow-2xl max-w-md w-full p-6 flex flex-col gap-4">
            <div className="flex items-center justify-between border-b border-[#0E0D0B]/10 pb-3">
              <div className="flex items-center gap-2">
                {modalState.type === 'success' ? (
                  <CheckCircle2 size={18} className="text-[#06C167]" />
                ) : (
                  <AlertCircle size={18} className="text-[#D93B2B]" />
                )}
                <h2 className="font-bold text-base text-[#0E0D0B]" style={{ fontFamily: 'Fraunces, serif' }}>
                  {modalState.title}
                </h2>
              </div>
              <button
                onClick={handleModalClose}
                className="text-[#0E0D0B]/50 hover:text-[#0E0D0B] transition-colors cursor-pointer"
              >
                <X size={16} />
              </button>
            </div>

            <p className="font-mono text-xs text-[#0E0D0B]/80 leading-relaxed">
              {modalState.message}
            </p>

            <div className="pt-2 flex justify-end">
              <Button
                variant="primary"
                size="sm"
                onClick={handleModalClose}
                className="font-mono text-[10px] uppercase tracking-widest px-4 py-1.5"
              >
                {modalState.type === 'success' ? 'Got It' : 'Close'}
              </Button>
            </div>
          </div>
        </div>
      )}
    </>
  )
}